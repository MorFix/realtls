#!/usr/bin/env node
/**
 * Bump native/binaries.json to a uTLS (bogdanfinn/tls-client) release, refreshing every
 * per-platform sha256.
 *
 *   node scripts/bump-binaries.mjs            # -> latest release
 *   node scripts/bump-binaries.mjs 1.15.1     # -> a specific version
 *
 * The platform -> asset-filename mapping lives here (the source of truth); binaries.json is
 * the generated output consumed by prepare-binaries.mjs and the runtime platform keys.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const REPO = 'bogdanfinn/tls-client';

// key -> { file(version) => asset name, os, cpu, libc? }
const PLATFORMS = {
    'darwin-arm64': { file: (v) => `tls-client-darwin-arm64-${v}.dylib`, os: 'darwin', cpu: 'arm64' },
    'darwin-x64': { file: (v) => `tls-client-darwin-amd64-${v}.dylib`, os: 'darwin', cpu: 'x64' },
    'linux-x64-glibc': { file: (v) => `tls-client-linux-ubuntu-amd64-${v}.so`, os: 'linux', cpu: 'x64', libc: 'glibc' },
    'linux-x64-musl': { file: (v) => `tls-client-linux-alpine-amd64-${v}.so`, os: 'linux', cpu: 'x64', libc: 'musl' },
    'linux-arm64': { file: (v) => `tls-client-linux-arm64-${v}.so`, os: 'linux', cpu: 'arm64' },
    'win32-x64': { file: (v) => `tls-client-windows-64-${v}.dll`, os: 'win32', cpu: 'x64' },
};

async function resolveVersion(arg) {
    if (arg && arg !== 'latest') return arg.replace(/^v/, '');
    const res = await fetch(`https://api.github.com/repos/${REPO}/releases/latest`, {
        headers: { accept: 'application/vnd.github+json', 'user-agent': 'realtls-bump' },
    });
    if (!res.ok) throw new Error(`GitHub API ${res.status} resolving latest release`);
    const json = await res.json();
    return String(json.tag_name).replace(/^v/, '');
}

async function sha256(url) {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) throw new Error(`download ${url} -> ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    return { sha: createHash('sha256').update(buf).digest('hex'), size: buf.length };
}

async function main() {
    const version = await resolveVersion(process.argv[2]);
    const releaseBase = `https://github.com/${REPO}/releases/download/v${version}`;
    console.log(`Bumping to uTLS v${version}`);

    const assets = {};
    for (const [key, meta] of Object.entries(PLATFORMS)) {
        const file = meta.file(version);
        const { sha, size } = await sha256(`${releaseBase}/${file}`);
        assets[key] = { file, sha256: sha, os: meta.os, cpu: meta.cpu, ...(meta.libc ? { libc: meta.libc } : {}) };
        console.log(`  ${key.padEnd(16)} ${file}  ${sha}  (${(size / 1e6).toFixed(1)} MB)`);
    }

    const out = {
        _comment:
            'Build-time manifest for the per-platform @realtls/native-* packages. Generated by scripts/bump-binaries.mjs. The prepare-binaries script downloads each uTLS shared library, verifies its sha256, and writes it into packages/<key>/.',
        version,
        releaseBase,
        assets,
    };
    const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'binaries.json');
    writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
    console.log(`Wrote ${dest}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
